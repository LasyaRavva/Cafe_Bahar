export const filterMenuItems = (items, active = 'All', query = '') => {
  const term = query.trim().toLocaleLowerCase();
  return items.filter(item =>
    (active === 'All' || item.category === active) &&
    (!term || `${item.name} ${item.category}`.toLocaleLowerCase().includes(term))
  );
};

export const formatMenuPrice = value => typeof value === 'number' ? `₹${value}` : value;
